pub async fn admin_bulk_translate(
    State(db): State<Database>,
) -> (StatusCode, Json<Value>) {
    bulk_translate_all_content(&db).await;
    (
        StatusCode::OK,
        Json(serde_json::json!({
            "success": true,
            "message": "Bulk translation started"
        })),
    )
}

