const MAX_TRANSLATE_CHARS: usize = 8192;

#[derive(Debug, Deserialize)]
pub struct TranslateRequest {
    pub text: String,
    /// Accept `target` or `target_lang` (frontend uses `target_lang`).
    #[serde(default, alias = "target_lang")]
    pub target: Option<String>,
}

#[derive(Debug, Deserialize)]
pub struct BulkTranslateRequest {
    pub text: String,
    pub languages: Vec<String>,
}

#[derive(Debug, Serialize)]
pub struct TranslateResponse {
    pub translated: String,
}

#[derive(Debug, Serialize)]
pub struct TranslateError {
    pub message: String,
}

fn infer_target_lang(payload_target: Option<&str>, headers: &HeaderMap) -> String {
    if let Some(target) = payload_target.filter(|v| !v.trim().is_empty()) {
        return normalize_lang(target);
    }

    if let Some(lang_header) = headers.get("Accept-Language").and_then(|v| v.to_str().ok()) {
        let first = lang_header.split(',').next().unwrap_or("en");
        return normalize_lang(first);
    }

    "en".to_string()
}

pub async fn translate_text(
    State(db): State<Database>,
    headers: HeaderMap,
    Json(payload): Json<TranslateRequest>,
) -> (StatusCode, Json<Value>) {
    let ip = client_ip(&headers);
    let limiter = IpRateLimit {
        limit: 40,
        window: Duration::from_secs(60),
    };
    if !check_rate_limit(&format!("translate:{ip}"), &limiter) {
        return (
            StatusCode::TOO_MANY_REQUESTS,
            Json(serde_json::json!(TranslateError {
                message: "Rate limit exceeded".to_string()
            })),
        );
    }

    let text = payload.text.trim().to_string();
    if text.is_empty() {
        return (
            StatusCode::BAD_REQUEST,
            Json(serde_json::json!(TranslateError {
                message: "Text is required".to_string()
            })),
        );
    }
    if text.chars().count() > MAX_TRANSLATE_CHARS {
        return (
            StatusCode::PAYLOAD_TOO_LARGE,
            Json(serde_json::json!(TranslateError {
                message: format!("Text exceeds maximum length ({MAX_TRANSLATE_CHARS} characters)")
            })),
        );
    }

    let target = infer_target_lang(payload.target.as_deref(), &headers);
    if target == "en" {
        return (
            StatusCode::OK,
            Json(serde_json::json!(TranslateResponse { translated: text })),
        );
    }

    match get_translation(&db, &text, &target).await {
        Ok(translated) => (
            StatusCode::OK,
            Json(serde_json::json!(TranslateResponse { translated })),
        ),
        Err(message) => (
            StatusCode::BAD_GATEWAY,
            Json(serde_json::json!(TranslateError { message })),
        ),
    }
}

pub async fn translate_bulk(
    State(db): State<Database>,
    headers: HeaderMap,
    Json(payload): Json<BulkTranslateRequest>,
) -> (StatusCode, Json<Value>) {
    let ip = client_ip(&headers);
    let limiter = IpRateLimit {
        limit: 25,
        window: Duration::from_secs(60),
    };
    if !check_rate_limit(&format!("translate_bulk:{ip}"), &limiter) {
        return (
            StatusCode::TOO_MANY_REQUESTS,
            Json(serde_json::json!(TranslateError {
                message: "Rate limit exceeded".to_string()
            })),
        );
    }

    let text = payload.text.trim().to_string();
    if text.is_empty() {
        return (
            StatusCode::BAD_REQUEST,
            Json(serde_json::json!(TranslateError {
                message: "Text is required".to_string()
            })),
        );
    }
    if text.chars().count() > MAX_TRANSLATE_CHARS {
        return (
            StatusCode::PAYLOAD_TOO_LARGE,
            Json(serde_json::json!(TranslateError {
                message: format!("Text exceeds maximum length ({MAX_TRANSLATE_CHARS} characters)")
            })),
        );
    }
    if payload.languages.is_empty() {
        return (
            StatusCode::BAD_REQUEST,
            Json(serde_json::json!(TranslateError {
                message: "languages[] is required".to_string()
            })),
        );
    }

    let supported = get_supported_languages();
    let langs: Vec<String> = payload
        .languages
        .iter()
        .map(|l| normalize_lang(l))
        .filter(|l| supported.contains(&l.as_str()))
        .collect();

    let out = bulk_translate(&db, &text, &langs).await;
    (StatusCode::OK, Json(serde_json::json!(out)))
}
